def main() -> None:
    """同步章内事件、分步实训、题库与模块规则，保留本人代码。"""
    catalog = load_catalog()
    path = ROOT / "instructor/course_enrichment.json"
    content = json.loads(path.read_text())
    story = (ROOT / "world/STORY.md").read_text()
    for module in catalog["modules"]:
        mid = module["id"]
        tasks = [t for t in catalog["tasks"] if t["module"] == mid]
        last = tasks[-1]
        opening = content["modules"][mid]["opening"].split("\n\n### 林禾的机构委托")[0]
        content["modules"][mid]["opening"] = opening + "\n\n### 林禾的机构委托\n\n" + INCIDENTS[mid]
        pattern = rf"(## {mid} .*?\n\n)(.*?)(\n\n\*\*本章实际委托：\*\*)"

        def insert_chapter(
            match: re.Match[str], opening: str = content["modules"][mid]["opening"]
        ) -> str:
            return match[1] + opening + match[3]

        story, count = re.subn(
            pattern,
            insert_chapter,
            story,
            count=1,
            flags=re.DOTALL,
        )
        if count != 1:
            raise ValueError("故事章节定位失败：" + mid)
        notebook_path = ROOT / last["notebook"]
        notebook = nbformat.read(notebook_path, as_version=4)
        source = "## 生产实训分三次接通\n\n每次约一小时，可在任一步保存。读完整示范后再做本人项目，不要求一次接完。\n\n"
        source += "\n\n".join(f"**阶段{i}：** {step}" for i, step in enumerate(STEPS[mid], 1))
        item = next((c for c in notebook.cells if c.id == "enterprise-staged-practice"), None)
        if item:
            item.source = source
        else:
            index = next(
                i for i, c in enumerate(notebook.cells) if c.id == "enterprise-owned-project"
            )
            notebook.cells.insert(index, cell("markdown", source, "enterprise-staged-practice"))
        nbformat.write(notebook, notebook_path)
        quiz = content["tasks"][last["id"]]["quiz"]
        quiz[:] = [q for q in quiz if "-enterprise-" not in q["id"]]
        for i, (prompt, right, explanation, wrong_a, feedback_a, wrong_b, feedback_b) in enumerate(
            QUESTIONS[mid], 1
        ):
            correct = "B" if i % 2 else "C"
            options = [
                {"id": "A", "label": wrong_a, "feedback": feedback_a},
                {
                    "id": "B",
                    "label": right if correct == "B" else wrong_b,
                    "feedback": explanation if correct == "B" else feedback_b,
                },
                {
                    "id": "C",
                    "label": right if correct == "C" else wrong_b,
                    "feedback": explanation if correct == "C" else feedback_b,
                },
            ]
            quiz.append(
                {
                    "id": last["id"] + f"-enterprise-{i}",
                    "concept": "生产边界与证据",
                    "prompt": "林禾在章末接待台问：" + prompt,
                    "correct": correct,
                    "options": options,
                }
            )
        rules = ROOT / module["directory"] / "AGENTS.md"
        base = rules.read_text().split("\n## 本模块生产实训协议")[0]
        supplement = "\n## 本模块生产实训协议\n\n"
        supplement += f"业务项目见instructor/blueprints/{mid}.md与module_blueprints.json，完整原理在首关Notebook，真实实训在{last['id']}。本章有三层路线，不预设企业后端经验；新对象/API原位解释。\n\n"
        supplement += "\n\n".join(f"**授课阶段{i}：**{s}" for i, s in enumerate(STEPS[mid], 1))
        supplement += "\n\nproduction-cases.json记录本章目标案例，enterprise-owned-checks调用本人module_agent并提供独立CaseEnvironment。教师准备与本人事件分开，目标不传runtime；审批token不进消息或公开包。窄检查、语义核对与陌生迁移分别记录，manual_review_required不自动通关。\n\n"
        supplement += "不让本人的组件回退到enterprise教师进程；缺本人实现定位原格。当前身份、来源版本、许可与累计预算跨本章完整作品保留。章节事件以course_enrichment/world/STORY为共同说明，故障由实际环境触发，故事不决定通过。维护须运行enterprise_course（结构改变时）、render_curriculum、check与对应真实验证；不提交、推送或修改完成状态。\n"
        if mid == "M01":
            base = base.replace("门厅有两项连续委托。", "门厅有三项连续委托。")
        rules.write_text(base.rstrip() + "\n" + supplement)
    write_json(path, content)
    (ROOT / "world/STORY.md").write_text(story)
    print("十章机构委托、三段实训、20张判断卡与模块协议已同步。")


if __name__ == "__main__":
    main()
